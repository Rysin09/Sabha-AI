"""
backend/services/export_service.py
────────────────────────────────────
PDF and TXT export logic for meeting reports.
Uses reportlab for PDF generation.
"""
import io
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, HRFlowable, Table, TableStyle
)
from reportlab.lib.enums import TA_LEFT, TA_CENTER


def _clean(text: str) -> str:
    """Escape XML special chars for ReportLab paragraphs."""
    return (text
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;"))


def generate_pdf(report: dict) -> bytes:
    """
    Generate a PDF byte stream from a meeting report dict.

    Expected keys: title, source, language, summary, action_items,
                   key_decisions, open_questions, transcript, processed_at
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=2 * cm,
        rightMargin=2 * cm,
        topMargin=2 * cm,
        bottomMargin=2 * cm,
    )

    styles = getSampleStyleSheet()

    # ── Custom styles ─────────────────────────────────────────────────────────
    title_style = ParagraphStyle(
        "SabhaTitle",
        parent=styles["Title"],
        fontSize=22,
        textColor=colors.HexColor("#6C63FF"),
        spaceAfter=6,
        alignment=TA_CENTER,
    )
    subtitle_style = ParagraphStyle(
        "SabhaSubtitle",
        parent=styles["Normal"],
        fontSize=10,
        textColor=colors.HexColor("#888888"),
        spaceAfter=2,
        alignment=TA_CENTER,
    )
    section_style = ParagraphStyle(
        "SabhaSection",
        parent=styles["Heading2"],
        fontSize=13,
        textColor=colors.HexColor("#2D2D4E"),
        spaceBefore=14,
        spaceAfter=6,
        borderPad=4,
    )
    body_style = ParagraphStyle(
        "SabhaBody",
        parent=styles["Normal"],
        fontSize=10,
        leading=16,
        textColor=colors.HexColor("#333333"),
    )
    meta_style = ParagraphStyle(
        "SabhaMeta",
        parent=styles["Normal"],
        fontSize=9,
        textColor=colors.HexColor("#666666"),
    )

    story = []

    # ── Header ────────────────────────────────────────────────────────────────
    story.append(Spacer(1, 0.3 * cm))
    story.append(Paragraph("SABHA AI", title_style))
    story.append(Paragraph("Meeting Intelligence Report", subtitle_style))
    story.append(Spacer(1, 0.2 * cm))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#6C63FF")))
    story.append(Spacer(1, 0.4 * cm))

    # ── Meeting title & metadata ───────────────────────────────────────────────
    story.append(Paragraph(_clean(report.get("title", "Untitled Meeting")), section_style))
    story.append(Paragraph(f"<b>Source:</b> {_clean(report.get('source', ''))}", meta_style))
    story.append(Paragraph(f"<b>Language:</b> {_clean(report.get('language', 'english').title())}", meta_style))
    story.append(Paragraph(f"<b>Processed:</b> {_clean(report.get('processed_at', ''))}", meta_style))
    story.append(Spacer(1, 0.4 * cm))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CCCCCC")))

    def add_section(heading: str, content: str):
        story.append(Paragraph(heading, section_style))
        for line in content.strip().split("\n"):
            stripped = line.strip()
            if stripped:
                story.append(Paragraph(_clean(stripped), body_style))
                story.append(Spacer(1, 0.1 * cm))
        story.append(Spacer(1, 0.2 * cm))

    add_section("📋 Summary", report.get("summary", ""))
    add_section("✅ Action Items", report.get("action_items", ""))
    add_section("🎯 Key Decisions", report.get("key_decisions", ""))
    add_section("❓ Open Questions & Follow-ups", report.get("open_questions", ""))

    # ── Transcript (truncated if very long) ───────────────────────────────────
    transcript = report.get("transcript", "")
    if len(transcript) > 6000:
        transcript = transcript[:6000] + "\n\n[Transcript truncated — full version available in TXT export]"
    add_section("📝 Transcript", transcript)

    # ── Footer ────────────────────────────────────────────────────────────────
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CCCCCC")))
    story.append(Spacer(1, 0.2 * cm))
    story.append(Paragraph(
        f"Generated by Sabha AI · {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
        subtitle_style,
    ))

    doc.build(story)
    return buffer.getvalue()


def generate_txt(report: dict) -> str:
    """Generate a plain-text meeting report string."""
    lines = [
        "=" * 70,
        "  SABHA AI — MEETING INTELLIGENCE REPORT",
        "=" * 70,
        "",
        f"Title     : {report.get('title', 'Untitled Meeting')}",
        f"Source    : {report.get('source', '')}",
        f"Language  : {report.get('language', 'english').title()}",
        f"Processed : {report.get('processed_at', '')}",
        "",
        "-" * 70,
        "SUMMARY",
        "-" * 70,
        report.get("summary", ""),
        "",
        "-" * 70,
        "ACTION ITEMS",
        "-" * 70,
        report.get("action_items", ""),
        "",
        "-" * 70,
        "KEY DECISIONS",
        "-" * 70,
        report.get("key_decisions", ""),
        "",
        "-" * 70,
        "OPEN QUESTIONS & FOLLOW-UPS",
        "-" * 70,
        report.get("open_questions", ""),
        "",
        "-" * 70,
        "FULL TRANSCRIPT",
        "-" * 70,
        report.get("transcript", ""),
        "",
        "=" * 70,
        f"Generated by Sabha AI · {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
        "=" * 70,
    ]
    return "\n".join(lines)
